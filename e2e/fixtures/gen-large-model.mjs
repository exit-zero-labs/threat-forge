#!/usr/bin/env node
/**
 * Regenerate `e2e/fixtures/large-model.thf`, the "large" workspace fixture (issue #65, D8).
 *
 * Not wired into any npm script or CI step — run manually to regenerate:
 *
 *   node e2e/fixtures/gen-large-model.mjs
 *
 * Shape (do not change without updating docs/plans/65-browser-workspace-fixtures.md D8 and
 * bumping `WORKSPACE_FIXTURE_VERSION` in `e2e/support/workspace-fixtures.ts`):
 *
 * - 150 elements, 100 data flows, current schema version "1.0".
 * - Deterministic grid layout: 15 columns x 10 rows, 220px column spacing, 160px row spacing, so
 *   `buildLayoutFromModel` positions every node from its explicit `position` and no auto-layout
 *   algorithm runs.
 * - No `source_handle`/`target_handle` on any flow. Confirmed empirically (see the plan's
 *   "fixture authoring pitfall") that bare position-name handles — the way the shared `.thf`
 *   round-trip corpus's `architecture-canonical-full.thf` does — reintroduce a ReactFlow
 *   "Couldn't create edge for source handle id" console warning once the DOM handle-id
 *   convention (`{position}-source`/`{position}-target`) does not match. Omitting handles
 *   entirely renders an un-anchored edge with zero console noise, which is what this fixture
 *   needs to stay clean under the failure-aware test base (`support/base.ts`).
 * - No duplicate element or flow ids, and every flow's `from`/`to` references a real element id
 *   (the same reference-integrity rules `thf-validation.ts` enforces).
 * - Distinct `(from, to)` pairs per flow, so 100 flows render as 100 distinct `.react-flow__edge`
 *   elements rather than some pairs coinciding.
 *
 * Lives at `e2e/fixtures/`, not `tests/fixtures/thf/`: that directory's own README scopes it
 * strictly to the shared Rust/TS byte-identity/round-trip corpus; this is an e2e-only bulk fixture
 * with a different contract (render performance, not exact byte/handle geometry).
 */

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { dump } from "js-yaml";

const COLUMNS = 15;
const ROWS = 10;
const ELEMENT_COUNT = COLUMNS * ROWS; // 150
const FLOW_COUNT = 100;
const COLUMN_SPACING = 220;
const ROW_SPACING = 160;
const ORIGIN_X = 100;
const ORIGIN_Y = 100;
const FIXTURE_DATE = "2026-01-01";

function elementId(index) {
	return `element-${String(index).padStart(3, "0")}`;
}

function flowId(index) {
	return `flow-${String(index).padStart(3, "0")}`;
}

function buildElements() {
	const elements = [];
	for (let i = 0; i < ELEMENT_COUNT; i++) {
		const column = i % COLUMNS;
		const row = Math.floor(i / COLUMNS);
		elements.push({
			id: elementId(i),
			type: "generic",
			name: `Element ${i}`,
			trust_zone: "internal",
			description: "Synthetic element for the large-workspace E2E fixture (issue #65).",
			technologies: [],
			position: {
				x: ORIGIN_X + column * COLUMN_SPACING,
				y: ORIGIN_Y + row * ROW_SPACING,
			},
		});
	}
	return elements;
}

function buildDataFlows() {
	const flows = [];
	for (let i = 0; i < FLOW_COUNT; i++) {
		flows.push({
			id: flowId(i),
			name: `Flow ${i}`,
			from: elementId(i),
			to: elementId(i + 1),
			protocol: "HTTPS",
			data: [],
			authenticated: false,
		});
	}
	return flows;
}

function buildModel() {
	return {
		version: "1.0",
		metadata: {
			title: "Large Synthetic Workspace",
			author: "",
			created: FIXTURE_DATE,
			modified: FIXTURE_DATE,
			description:
				"Generated by e2e/fixtures/gen-large-model.mjs for the #65 large-workspace fixture: " +
				`${ELEMENT_COUNT} elements, ${FLOW_COUNT} data flows, a deterministic ${COLUMNS}x${ROWS} grid.`,
		},
		elements: buildElements(),
		data_flows: buildDataFlows(),
		trust_boundaries: [],
		threats: [],
		diagrams: [{ id: "main-dfd", name: "Level 0 DFD" }],
	};
}

function main() {
	const header = [
		"# ThreatForge Threat Model",
		"# Large synthetic workspace fixture for browser E2E (issue #65, D8).",
		"# Generated by e2e/fixtures/gen-large-model.mjs — do not hand-edit; regenerate instead.",
		`# ${ELEMENT_COUNT} elements, ${FLOW_COUNT} data flows, ${COLUMNS}x${ROWS} grid, fixture version 1.`,
		"",
	].join("\n");

	const body = dump(buildModel(), { lineWidth: 100 });
	const outPath = join(dirname(fileURLToPath(import.meta.url)), "large-model.thf");
	writeFileSync(outPath, `${header}${body}`, "utf-8");
	console.log(`Wrote ${outPath}`);
}

main();
